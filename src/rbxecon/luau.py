"""Export de la config vers un module Luau : le jeu utilise exactement les chiffres simulés."""

from __future__ import annotations

from .config import Config, Item


def _s(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "") + '"'


def _n(x: float) -> str:
    if x == int(x) and abs(x) < 1e15:
        return str(int(x))
    return repr(float(x))


def _item(it: Item) -> str:
    reqs = ", ".join(f"{{ item = {_s(r)}, count = {c} }}" for r, c in it.requires)
    fields = [
        f"name = {_s(it.name)}",
        f"kind = {_s(it.kind)}",
        f"cost = {_n(it.cost)}",
        f"costGrowth = {_n(it.cost_growth)}",
        f"max = {it.max}",
        f"income = {_n(it.income)}",
        f"multiplier = {_n(it.multiplier)}",
        f"group = {_s(it.group)}",
    ]
    if it.applies_to is not None:
        fields.append(f"appliesTo = {_s(it.applies_to)}")
    fields.append(f"requires = {{ {reqs} }}" if reqs else "requires = {}")
    body = ",\n\t\t".join(fields)
    return f"\t[{_s(it.name)}] = {{\n\t\t{body},\n\t}},"


def to_luau(cfg: Config) -> str:
    order = ", ".join(_s(it.name) for it in cfg.items)
    items = "\n".join(_item(it) for it in cfg.items)
    src = f' from "{cfg.source}"' if cfg.source else ""
    return f'''--!strict
-- Generated by rbxecon{src}. Do not edit by hand:
-- change the TOML file and run `rbxecon luau` again.

export type Requirement = {{ item: string, count: number }}

export type Item = {{
	name: string,
	kind: string, -- "income" or "multiplier"
	cost: number,
	costGrowth: number,
	max: number,
	income: number,
	multiplier: number,
	group: string,
	appliesTo: string?,
	requires: {{ Requirement }},
}}

local Economy = {{}}

Economy.StartCash = {_n(cfg.start_cash)}
Economy.BaseIncome = {_n(cfg.base_income)}
Economy.RoundCosts = {"true" if cfg.round_costs else "false"}

-- Same order as the config file.
Economy.Order = {{ {order} }}

Economy.Items = {{
{items}
}} :: {{ [string]: Item }}

-- Price of the next copy when the player already owns `owned` copies.
function Economy.getCost(name: string, owned: number): number
	local item = Economy.Items[name]
	assert(item, "Unknown item: " .. name)
	local raw = item.cost * item.costGrowth ^ owned
	if Economy.RoundCosts then
		return math.floor(raw + 0.5)
	end
	return raw
end

-- True when every requirement of the item is met. `owned` maps item name -> count.
function Economy.isUnlocked(name: string, owned: {{ [string]: number }}): boolean
	local item = Economy.Items[name]
	assert(item, "Unknown item: " .. name)
	for _, req in item.requires do
		if (owned[req.item] or 0) < req.count then
			return false
		end
	end
	return true
end

-- Money earned per second for the given purchases.
function Economy.incomePerSecond(owned: {{ [string]: number }}): number
	local sums: {{ [string]: number }} = {{ base = Economy.BaseIncome }}
	local multAll = 1
	local multGroup: {{ [string]: number }} = {{}}
	for _, name in Economy.Order do
		local item = Economy.Items[name]
		local n = owned[name] or 0
		if n > 0 then
			if item.kind == "income" then
				sums[item.group] = (sums[item.group] or 0) + item.income * n
			else
				local target = item.appliesTo
				if target == nil then
					multAll *= item.multiplier ^ n
				else
					multGroup[target] = (multGroup[target] or 1) * item.multiplier ^ n
				end
			end
		end
	end
	local total = 0
	for group, value in sums do
		total += value * (multGroup[group] or 1)
	end
	return total * multAll
end

return Economy
'''
